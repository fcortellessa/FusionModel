def analyze_single_run(df, output_dir: Path, fmt: str = "png"):
    """Generates exhaustive diagnostic plots for an isolated execution run."""
    output_dir.mkdir(parents=True, exist_ok=True)
    
    if fmt == "html_plotly":
        generate_plotly_single_run(df, "diagnostics", output_dir)
        print(f"All 7 Interactive Plotly HTML diagnostics saved inside directory: {output_dir}")
        return

    ext = f".{fmt}"
    for zoom in [False, True]:
        suffix = "_zoom30" if zoom else ""
        
        # 1. TRAIN VS VAL LOSS
        fig, ax = plt.subplots(figsize=(10, 4.5))
        plot_train_val(df, ax, "epoch", "train_loss", "val_loss", "Train vs Validation Loss Convergence", "Loss Value", zoom_last_30=zoom)
        if "train_loss" in df.columns and not zoom:
            best_idx = df["train_loss"].idxmin()
            ax.annotate(f"Best Train: {df.loc[best_idx, 'train_loss']:.3f}", 
                        (df.loc[best_idx, "epoch"], df.loc[best_idx, "train_loss"]),
                        xytext=(10, 10), textcoords='offset points', arrowprops=dict(arrowstyle="->", alpha=0.5))
        ax.set_xlabel("Epoch")
        add_run_metadata(fig, df)
        plt.tight_layout()
        plt.savefig(output_dir / f"loss_convergence{suffix}{ext}", dpi=150)
        plt.close()

