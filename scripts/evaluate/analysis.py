def generate_plotly_ablation(master_history: pd.DataFrame, variants: list, metrics_to_benchmark: list, output_dir: Path):
    """Renders interactive comparative ablation curves via Plotly with CDN JS linkage."""
    if not PLOTLY_AVAILABLE:
        print("Warning: Plotly is not installed. Skipping comparative HTML widget generation.")
        return

    for metric in metrics_to_benchmark:
        fig = go.Figure()
        for variant in variants:
            v_df = master_history[master_history['variant'] == variant].dropna(subset=[metric])
            if v_df.empty:
                continue
            stats = v_df.groupby('epoch')[metric].agg(['mean', 'std']).reset_index()
            fig.add_trace(go.Scatter(x=stats['epoch'], y=stats['mean'], mode='lines', name=variant))
            
        fig.update_layout(
            title=f"Ablation Performance Comparison: {metric}",
            xaxis_title="Epoch",
            yaxis_title=metric,
            template="plotly_white"
        )
        fig.write_html(str(output_dir / f"ablation_comparison_{metric}.html"), include_plotlyjs='cdn')


def analyze_folder_ablation(runs_dir: Path, output_dir: Path, fmt: str = "png"):
    """Finds all child runs, isolates configuration edits, and plots comparative curves."""
    metrics_files = glob.glob(os.path.join(str(runs_dir), "*/metrics.csv"))
    if not metrics_files:
        print(f"Error: No run configurations holding metrics.csv discovered inside {runs_dir}")
        return

    all_histories = []
    all_configs = {}

    for path in metrics_files:
        run_name = os.path.basename(os.path.dirname(path))
        config_path = Path(os.path.dirname(path)) / "config.yml"
        
        flat_config = {}
        if config_path.exists():
            try:
                with open(config_path, "r") as f:
                    flat_config = flatten_dict(yaml.safe_load(f) or {})
            except Exception as e:
                print(f"Warning: Configuration extraction failure on run '{run_name}': {e}")
        all_configs[run_name] = flat_config

        try:
            run_df = pd.read_csv(path)
            if not run_df.empty:
                run_df["run_name"] = run_name
                all_histories.append(run_df)
        except Exception as e:
            print(f"Error reading metrics matrix for run folder '{run_name}': {e}")

    if not all_histories:
        return

    config_df = pd.DataFrame.from_dict(all_configs, orient='index')
    ignore_keys = [
        "data.augmentation.seed",
        "training.task_weighting.init_log_var_rot",
        "training.task_weighting.init_log_var_trans",
        "training.uncertainty_weighting.init_log_var_rot",
        "training.uncertainty_weighting.init_log_var_trans",
        "seed",
        # Computed per-run from that run's own train split (see
        # compute_translation_norm_stats); differs slightly run-to-run even when
        # nothing experimentally meaningful changed, so it's not a real ablated
        # variable and would otherwise pollute the auto-detected variant labels.
        "data.translation_norm_stats.mean_y",
        "data.translation_norm_stats.std_y",
        "data.translation_norm_stats.mean_z",
        "data.translation_norm_stats.std_z",
    ]
    config_df = config_df.drop(columns=[c for c in ignore_keys if c in config_df.columns], errors='ignore')
    
    unique_counts = config_df.nunique()
    ablated_keys = unique_counts[unique_counts > 1].index.tolist()

    variant_mapping = {}
    for run_name, cfg in all_configs.items():
        if ablated_keys:
            variant_mapping[run_name] = " | ".join([f"{k}={cfg.get(k, 'N/A')}" for k in ablated_keys])
        else:
            variant_mapping[run_name] = run_name

    master_history = pd.concat(all_histories, ignore_index=True)
    master_history["variant"] = master_history["run_name"].map(variant_mapping)

    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Generate performance summaries sorted by Rot + Trans L2
    generate_ablation_summary(master_history, runs_dir=runs_dir, output_dir=output_dir.parent)
    
    variants = master_history['variant'].unique()
    metrics_to_benchmark = [col for col in ['train_loss', 'epoch_time_sec', 'val_abs_rot_x', 'val_abs_y', 'val_abs_z'] if col in master_history.columns]

    if fmt == "html_plotly":
        generate_plotly_ablation(master_history, variants, metrics_to_benchmark, output_dir)
        print(f"Multi-run Plotly HTML ablation plots saved inside target folder: {output_dir}")
        return

    ext = f".{fmt}"
    cmap = plt.get_cmap('tab10')
    colors = {v: cmap(i % 10) for i, v in enumerate(variants)}

    for zoom in [False, True]:
        suffix = "_zoom30" if zoom else ""
        
        for metric in metrics_to_benchmark:
            fig, ax = plt.subplots(figsize=(10, 5))
            for variant in variants:
                v_df = master_history[master_history['variant'] == variant].dropna(subset=[metric])
                if v_df.empty:
                    continue
                
                if zoom and v_df['epoch'].max() > 30:
                    max_epoch = v_df['epoch'].max()
                    v_df = v_df[v_df['epoch'] > (max_epoch - 30)]
                
                stats = v_df.groupby('epoch')[metric].agg(['mean', 'std']).reset_index()
                
                lbl = variant if len(variant) <= 30 else variant[:30] + "..."
                ax.plot(stats['epoch'], stats['mean'], label=lbl, color=colors[variant], linewidth=2)
                if 'std' in stats.columns and stats['std'].notna().any():
                    ax.fill_between(stats['epoch'], stats['mean'] - stats['std'], stats['mean'] + stats['std'], color=colors[variant], alpha=0.15)

            title_str = f"Ablation Performance Metric: Comparison of {metric}" + (" (Last 30 Epochs)" if zoom else "")
            ax.set_title(title_str, fontsize=12, fontweight='bold')
            ax.set_xlabel("Epoch")
            ax.set_ylabel(metric)
            ax.grid(True, linestyle='--', alpha=0.5)
            leg = ax.legend(bbox_to_anchor=(1.02, 1), loc='upper left', fontsize=8)
            
            plt.savefig(
                output_dir / f"ablation_comparison_{metric}{suffix}{ext}",
                dpi=150,
                bbox_extra_artists=(leg,), 
                bbox_inches='tight'
            )
            plt.close()
        
    print(f"Multi-run ablation bench plots saved inside target folder: {output_dir}")


